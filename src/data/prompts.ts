/**
 * お題（今日のお題）。
 *
 * 「何を書けばいいか分からない」で手が止まる子の入口。
 * MVP では固定プールから日替わりで 1 問を選ぶ。サーバ配信にはしない。
 *
 * お題を作るときの原則:
 *   - 家庭環境の差が出るもの（旅行、習い事、持ち物）は避ける
 *   - 見た目や成績を比べさせるものは入れない
 *   - 答えが 1 行で書けるものにする
 */
export const prompts: string[] = [
  'きょうの きゅうしょくで いちばん おいしかったのは？',
  'いま いちばん はまっている あそびは なに？',
  'もし まほうが つかえたら なにを する？',
  'すきな どうぶつと そのりゆうは？',
  'さいきん わらったことを おしえて！',
  'あしたの じぶんに ひとこと！',
  'たからものは なに？',
  'もし 1にち せんせいに なれたら なにを する？',
  'すきな きせつは？ どうして？',
  'いま いちばん たべたいものは？',
  'とくいなことを ひとつ おしえて！',
  'もし そらを とべたら どこへ いく？',
  'さいきん がんばったことは？',
  'すきな いろと、それで なにを かきたい？',
  'むしゃくしゃした とき どうやって なおす？',
  'ともだちに ありがとうを つたえるなら だれに？',
  'もし ペットが しゃべれたら なんて いうかな？',
  'ゆめの なかで みたことを おしえて！',
  'きょう みつけた ちいさな はっけんは？',
  'この ノートを よんでる ひとに しつもん！',
];

/**
 * 日付から決定的に 1 問を選ぶ。
 * グループ内の全員に同じお題が出るよう、乱数ではなく日付を種にする。
 */
export function promptOfTheDay(date = new Date()): string {
  const key =
    date.getFullYear() * 10000 + (date.getMonth() + 1) * 100 + date.getDate();
  return prompts[key % prompts.length];
}
